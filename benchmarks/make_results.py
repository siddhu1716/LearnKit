"""Regenerate the canonical LearnKit benchmark artifact.

This is the ONE command behind the reproducibility claim:

    python -m benchmarks.make_results            # derive RESULTS.json + RESULTS.md
    python -m benchmarks.make_results --check     # CI: fail if artifact is stale
    python -m benchmarks.make_results --run       # run the live matrix, then re-derive

`benchmarks/matrix_manifest.json` pins which committed raw suite-summary backs
each published model. This script loads those raw runs, normalizes them into a
single ``benchmarks/RESULTS.json`` (stable schema + provenance), and renders a
human-readable ``benchmarks/MATRIX.md`` table. Nothing here is hand-curated:
the numbers are read straight out of the raw benchmark output, so "clone → one
command → see the table" always reflects real runs.

Offline by default: with no ``--run`` flag it derives from the committed raw
JSON, so it works without the GPU cluster. ``--run`` reproduces from scratch
against the manifest's model endpoints, then re-pins the manifest to the fresh
runs before deriving.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent
REPO_ROOT = ROOT.parent
MANIFEST = ROOT / "matrix_manifest.json"
RESULTS_JSON = ROOT / "RESULTS.json"
RESULTS_MD = ROOT / "MATRIX.md"

GENERATED_NOTE = "GENERATED by `python -m benchmarks.make_results` — do not edit by hand."


def _pct(cold: int, warm: int) -> float:
    """Percentage reduction from cold to warm (0 when cold is 0)."""
    if not cold:
        return 0.0
    return round(100.0 * (cold - warm) / cold, 1)


def _load_manifest() -> dict[str, Any]:
    if not MANIFEST.exists():
        sys.exit(f"manifest not found: {MANIFEST}")
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def _normalize_model(entry: dict[str, Any]) -> dict[str, Any]:
    """Read a pinned raw suite-summary and project it onto the canonical row."""
    source = ROOT / entry["source"]
    if not source.exists():
        sys.exit(
            f"source run missing for {entry['name']}: {source}\n"
            "Fix the 'source' path in matrix_manifest.json or run with --run."
        )
    raw = json.loads(source.read_text(encoding="utf-8"))
    b = raw["benchmarks"]
    rl, ev, ij = b["react_live"], b["evolution_live"], b["injection_ablation"]
    gate = raw["gates"]["min_playbook_effect"]

    combined_cold = rl["cold_llm_calls"] + ev["cold_llm_calls"]
    combined_warm = rl["warmed_llm_calls"] + ev["warmed_llm_calls"]

    return {
        "name": entry["name"],
        "display": entry["display"],
        "model": entry["model"],
        "base_url": entry["base_url"],
        "gate": {
            "metric": "playbook_effect",
            "threshold": gate["threshold"],
            "observed": gate["observed"],
            "pass": bool(gate["pass"]),
        },
        "quality_lift": gate["observed"],
        "react": {
            "cold_llm_calls": rl["cold_llm_calls"],
            "warmed_llm_calls": rl["warmed_llm_calls"],
            "reduction_pct": _pct(rl["cold_llm_calls"], rl["warmed_llm_calls"]),
            "success": f"{rl['warmed_success']}/{rl['warmed_tasks']}",
        },
        "evolution": {
            "cold_llm_calls": ev["cold_llm_calls"],
            "warmed_llm_calls": ev["warmed_llm_calls"],
            "reduction_pct": _pct(ev["cold_llm_calls"], ev["warmed_llm_calls"]),
            "success": f"{ev['warmed_success']}/{ev['warmed_tasks']}",
            "evolved": bool(ev.get("evolved", False)),
        },
        "combined_llm_calls": {
            "cold": combined_cold,
            "warmed": combined_warm,
            "reduction_pct": _pct(combined_cold, combined_warm),
        },
        "injection": {
            "procedure_avg_score": ij["procedure_avg_score"],
            "playbook_avg_score": ij["playbook_avg_score"],
            "pass_k_full": ij["playbook_pass_k_full"],
        },
        "provenance": {
            "source": entry["source"],
            "run_generated_at": raw.get("generated_at"),
        },
    }


def build_results(manifest: dict[str, Any]) -> dict[str, Any]:
    rows = [_normalize_model(m) for m in manifest["models"]]
    passing = [r for r in rows if r["gate"]["pass"]]
    best = max(rows, key=lambda r: r["quality_lift"]) if rows else None
    # Headline call reduction: pooled across every passing model's react+evolution.
    pooled_cold = sum(r["combined_llm_calls"]["cold"] for r in passing)
    pooled_warm = sum(r["combined_llm_calls"]["warmed"] for r in passing)
    return {
        "_note": GENERATED_NOTE,
        "suite": manifest.get("suite", "agentic"),
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "gate": manifest["gate"],
        "run_config": manifest["run_config"],
        "reproduce_command": manifest["reproduce_command"],
        "summary": {
            "models_total": len(rows),
            "models_passing": len(passing),
            "best_quality_lift": best["quality_lift"] if best else None,
            "best_quality_lift_model": best["display"] if best else None,
            "pooled_llm_call_reduction_pct": _pct(pooled_cold, pooled_warm),
        },
        "models": rows,
    }


def render_markdown(results: dict[str, Any]) -> str:
    s = results["summary"]
    lines: list[str] = []
    lines.append("<!-- " + GENERATED_NOTE + " -->")
    lines.append("# LearnKit — Agentic Benchmark Matrix")
    lines.append("")
    lines.append(
        f"_Generated {results['generated_at']} from committed raw runs "
        f"(`benchmarks/matrix_manifest.json`)._"
    )
    lines.append("")
    lines.append(
        f"**{s['models_passing']}/{s['models_total']} models PASS** the "
        f"`{results['gate']['metric']} ≥ {results['gate']['threshold']}` gate. "
        f"Best quality lift **+{s['best_quality_lift']}** "
        f"({s['best_quality_lift_model']}); pooled LLM-call reduction across "
        f"passing models **−{s['pooled_llm_call_reduction_pct']}%**."
    )
    lines.append("")
    rc = results["run_config"]
    lines.append(
        f"Run config: trials={rc['trials']}, k={rc['k']}, seed={rc['seed']}, "
        f"temperature={rc['temperature']}, max_output_tokens={rc['max_output_tokens']}."
    )
    lines.append("")
    lines.append(
        "| Model | Gate | Quality lift | react LLM calls (cold→warm) | "
        "evolution LLM calls (cold→warm) | combined | Source |"
    )
    lines.append("|---|---|---|---|---|---|---|")
    for r in results["models"]:
        gate = "✓ PASS" if r["gate"]["pass"] else "✗ FAIL"
        rl, ev, cb = r["react"], r["evolution"], r["combined_llm_calls"]
        lines.append(
            f"| **{r['display']}** | {gate} | +{r['quality_lift']} | "
            f"{rl['cold_llm_calls']} → {rl['warmed_llm_calls']} (−{rl['reduction_pct']}%) | "
            f"{ev['cold_llm_calls']} → {ev['warmed_llm_calls']} (−{ev['reduction_pct']}%) | "
            f"{cb['cold']} → {cb['warmed']} (−{cb['reduction_pct']}%) | "
            f"`{r['provenance']['source']}` |"
        )
    lines.append("")
    lines.append("## Reproduce")
    lines.append("")
    lines.append("Derive this table from the committed raw runs (no GPU needed):")
    lines.append("")
    lines.append("```bash")
    lines.append("python -m benchmarks.make_results")
    lines.append("```")
    lines.append("")
    lines.append("Reproduce the numbers from scratch against live model endpoints:")
    lines.append("")
    lines.append("```bash")
    lines.append(results["reproduce_command"])
    lines.append("# then:")
    lines.append("python -m benchmarks.make_results --run")
    lines.append("```")
    lines.append("")
    lines.append(
        "`react_live` measures single-shot tool-call reduction (cold vs warmed); "
        "`evolution_live` measures multi-round durability; `injection_ablation` "
        "measures the quality lift from playbook injection (the gate)."
    )
    lines.append("")
    return "\n".join(lines)


def _write_artifact(results: dict[str, Any]) -> None:
    RESULTS_JSON.write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
    RESULTS_MD.write_text(render_markdown(results), encoding="utf-8")


def _strip_volatile(results: dict[str, Any]) -> dict[str, Any]:
    """Drop the timestamp so --check compares only substantive content."""
    clone = json.loads(json.dumps(results))
    clone.pop("generated_at", None)
    return clone


def _run_live_matrix(manifest: dict[str, Any], targets_override: list[str] | None = None) -> None:
    """Run the live matrix against manifest targets, then re-pin sources.

    ``targets_override`` is a list of "name|base_url|model" strings; when given
    it replaces the manifest's model list so users can benchmark THEIR OWN
    endpoints in one command.
    """
    rc = manifest["run_config"]
    if targets_override:
        parsed = []
        for t in targets_override:
            parts = [p.strip() for p in t.split("|", 2)]
            if len(parts) != 3 or not all(parts):
                sys.exit(f"--target must be 'name|base_url|model', got: {t}")
            parsed.append({"name": parts[0], "base_url": parts[1], "model": parts[2]})
        manifest["models"] = parsed
    targets = [
        f"{m['name']}|{m['base_url']}|{m['model']}" for m in manifest["models"]
    ]
    cmd = [
        sys.executable, "-m", "benchmarks.run_agentic_matrix",
        "--trials", str(rc["trials"]), "--k", str(rc["k"]),
        "--seed", str(rc["seed"]), "--continue-on-fail",
        "--per-model-timeout", "1800",
        "--react-timeout", "1500", "--evolution-timeout", "1500",
        "--injection-timeout", "1500",
    ]
    for t in targets:
        cmd += ["--target", t]
    print("Running live matrix:\n  " + " ".join(cmd))
    env = None
    proc = subprocess.run(cmd, cwd=str(REPO_ROOT), env=env)
    if proc.returncode not in (0, 2):  # 2 = a model failed a gate; still usable
        sys.exit(f"live matrix run failed (exit {proc.returncode})")

    # Re-pin each model to its newest per-model suite summary.
    results_dir = ROOT / "results"
    for m in manifest["models"]:
        matches = sorted(
            results_dir.glob(f"agentic_suite_{m['name']}_*_summary.json"),
            key=lambda p: p.stat().st_mtime,
        )
        if matches:
            m["source"] = f"results/{matches[-1].name}"
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Re-pinned manifest sources → {MANIFEST.name}")


def main() -> None:
    ap = argparse.ArgumentParser(description="Regenerate the benchmark artifact")
    ap.add_argument("--run", action="store_true",
                    help="Run the live matrix first, then derive from fresh runs")
    ap.add_argument("--target", action="append", metavar="name|base_url|model",
                    help="Benchmark your own endpoint (repeatable); implies --run")
    ap.add_argument("--check", action="store_true",
                    help="Exit non-zero if committed RESULTS are stale (CI guard)")
    args = ap.parse_args()

    manifest = _load_manifest()
    if args.run or args.target:
        _run_live_matrix(manifest, targets_override=args.target)
        manifest = _load_manifest()

    results = build_results(manifest)

    if args.check:
        if not RESULTS_JSON.exists():
            sys.exit("RESULTS.json missing — run `python -m benchmarks.make_results`.")
        current = json.loads(RESULTS_JSON.read_text(encoding="utf-8"))
        if _strip_volatile(current) != _strip_volatile(results):
            sys.exit(
                "RESULTS.json is stale. Run `python -m benchmarks.make_results` "
                "and commit the result."
            )
        print("RESULTS artifact is up to date.")
        return

    _write_artifact(results)
    s = results["summary"]
    print(
        f"Wrote {RESULTS_JSON.relative_to(REPO_ROOT)} and "
        f"{RESULTS_MD.relative_to(REPO_ROOT)}\n"
        f"  {s['models_passing']}/{s['models_total']} PASS · "
        f"best +{s['best_quality_lift']} ({s['best_quality_lift_model']}) · "
        f"pooled −{s['pooled_llm_call_reduction_pct']}% LLM calls"
    )


if __name__ == "__main__":
    main()
